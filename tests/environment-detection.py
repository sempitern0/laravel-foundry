"""Portable static and isolated regression checks for host-aware Compose overrides."""
from pathlib import Path
import os
import subprocess
import tempfile

root = Path(__file__).resolve().parents[1]
shell = root / 'scripts/environment.sh'
ps = root / 'scripts/environment.ps1'
assert shell.exists() and ps.exists()
assert 'compose.override.yaml' in shell.read_text()
assert 'compose.override.yaml' in ps.read_text()
assert 'rm -rf' not in shell.read_text()
assert 'down -v' not in shell.read_text()
assert 'CHOKIDAR_USEPOLLING' in shell.read_text()
assert 'CHOKIDAR_USEPOLLING' in ps.read_text()
assert 'linux-native' in shell.read_text() and 'wsl-windows-fs' in shell.read_text()
assert 'windows-native' in ps.read_text()
# Run against an isolated directory so it never changes the user's project.
with tempfile.TemporaryDirectory() as temp:
    work = Path(temp)
    (work / 'scripts').mkdir()
    (work / 'scripts/environment.sh').write_text(shell.read_text())
    run = lambda *args: subprocess.run(['sh',str(work/'scripts/environment.sh'),*args],
            cwd=work, text=True, capture_output=True, check=True)
    run('apply')
    override = work/'compose.override.yaml'
    first = override.read_text()
    assert first.startswith('# Generated by Laravel Foundry')
    assert 'services:' in first and 'app:' in first
    run('apply')
    assert override.read_text() == first
    override.write_text('# custom configuration\nservices: {}\n')
    run('apply')
    assert override.read_text() == '# custom configuration\nservices: {}\n'
    assert 'preserving' in run('apply').stderr
    run('doctor')
print('PASS host detection, idempotence and custom override protection')
