#!/usr/bin/env sh
# Laravel Foundry host detection. Does not require Docker or mutate project data.
set -eu
cd "$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)"
action=${1:-doctor}
override=compose.override.yaml
marker='# Generated by Laravel Foundry Environment Intelligence; do not edit.'
host=$(uname -s 2>/dev/null || echo unknown)
profile=portable
location=unknown
uid=1000
gid=1000
case "$host" in
  Linux)
    uid=$(id -u); gid=$(id -g)
    if grep -qi microsoft /proc/sys/kernel/osrelease 2>/dev/null || [ -n "${WSL_INTEROP:-}" ]; then
      profile=wsl-native
    else
      profile=linux-native
    fi
    path=$(pwd -P)
    case "$path" in
      /mnt/[a-zA-Z]/*)
        if [ "$profile" = wsl-native ]; then profile=wsl-windows-fs; fi
        location=windows-mounted
        ;;
      *)
        if command -v stat >/dev/null 2>&1; then
          fstype=$(stat -f -c %T . 2>/dev/null || echo unknown)
          case "$fstype" in
            9p|drvfs|fuseblk|cifs|ntfs|ntfs3) location=shared-filesystem ;;
            *) location=linux-filesystem ;;
          esac
        fi
        ;;
    esac
    ;;
  Darwin) profile=macos-native; location=desktop-shared ;;
  MINGW*|MSYS*|CYGWIN*) profile=windows-native; location=windows-mounted ;;
esac
if [ "$profile" = wsl-native ] && [ "$location" = shared-filesystem ]; then profile=wsl-windows-fs; fi
if [ "$profile" = linux-native ] && [ "$location" = shared-filesystem ]; then profile=linux-shared-fs; fi
managed() { [ -f "$override" ] && IFS= read -r first < "$override" && [ "$first" = "$marker" ]; }
write_override() {
  if [ -f "$override" ] && ! managed; then
    echo "Foundry: custom $override detected; preserving it. Automatic override not applied." >&2
    return 0
  fi
  # All generated settings are advisory host-specific overrides. Never modify root .env.
  if [ "$profile" = windows-native ] || [ "$profile" = wsl-windows-fs ] || [ "$profile" = linux-shared-fs ]; then
    polling=true
  else
    polling=false
  fi
  tmp=$(mktemp "./.foundry-host-override.XXXXXX")
  trap 'rm -f "$tmp"' EXIT HUP INT TERM
  {
    printf '%s\n' "$marker" '# Local-only Compose overrides. Regenerated at setup/up; ignored by Git.'
    printf 'services:\n'
    for service in app composer node worker scheduler; do
      printf '  %s:\n    user: "%s:%s"\n' "$service" "$uid" "$gid"
      if [ "$service" = node ] && [ "$polling" = true ]; then
        printf '    environment:\n      CHOKIDAR_USEPOLLING: "true"\n      CHOKIDAR_INTERVAL: "700"\n'
      fi
    done
  } > "$tmp"
  mv "$tmp" "$override"
  trap - EXIT HUP INT TERM
}
case "$action" in
  apply) write_override ;;
  doctor) : ;;
  *) echo 'Usage: environment.sh [apply|doctor]' >&2; exit 2 ;;
esac
printf 'Foundry host: %s | filesystem: %s | uid:gid %s:%s\n' "$profile" "$location" "$uid" "$gid"
case "$profile" in
  windows-native|wsl-windows-fs|linux-shared-fs)
    echo 'Advisory: source files on a Windows/shared filesystem can slow Laravel and Vite. Prefer a WSL2 Linux home directory where possible.'
    ;;
esac
if [ "$action" = doctor ]; then
  if command -v docker >/dev/null 2>&1; then
    docker info --format 'Docker Engine: {{.ServerVersion}}' 2>/dev/null || echo 'Docker Engine: unavailable'
  else echo 'Docker CLI: unavailable'; fi
  if [ -f "$override" ] && ! managed; then echo 'Compose override: custom (preserved)'; fi
fi
