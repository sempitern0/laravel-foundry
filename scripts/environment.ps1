[CmdletBinding()]
param([ValidateSet('Apply','Doctor')][string]$Mode = 'Doctor')
$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
$root = Split-Path -Parent $PSScriptRoot
$override = Join-Path $root 'compose.override.yaml'
$marker = '# Generated by Laravel Foundry Environment Intelligence; do not edit.'
$profile = 'windows-native'
$location = 'windows-mounted'
$uid = 1000
$gid = 1000
if ($PSVersionTable.PSVersion.Major -ge 6 -and -not $IsWindows) {
    if ($IsMacOS) { $profile = 'macos-native'; $location = 'desktop-shared' }
    elseif ($IsLinux) {
        $profile = 'linux-native'
        $location = 'linux-filesystem'
        $uid = [int](& id -u)
        $gid = [int](& id -g)
        if ((Test-Path '/proc/sys/kernel/osrelease') -and ((Get-Content '/proc/sys/kernel/osrelease' -Raw) -match 'microsoft')) {
            $profile = 'wsl-native'
            if ($root -match '^/mnt/[a-zA-Z]/') { $profile = 'wsl-windows-fs'; $location = 'windows-mounted' }
        }
    }
}
function Test-Managed {
    if (-not (Test-Path -LiteralPath $override)) { return $false }
    $first = Get-Content -LiteralPath $override -TotalCount 1
    return $first -ceq $marker
}
if ($Mode -eq 'Apply') {
    if ((Test-Path -LiteralPath $override) -and -not (Test-Managed)) {
        Write-Warning 'Custom compose.override.yaml detected; preserving it. Automatic override not applied.'
    } else {
        $lines = @($marker, '# Local-only Compose overrides. Regenerated at setup/up; ignored by Git.', 'services:')
        foreach ($service in @('app','composer','node','worker','scheduler')) {
            $lines += ('  {0}:' -f $service)
            $lines += ('    user: "{0}:{1}"' -f $uid,$gid)
            if ($service -eq 'node' -and $profile -in @('windows-native','wsl-windows-fs','linux-shared-fs')) {
                $lines += @('    environment:', '      CHOKIDAR_USEPOLLING: "true"', '      CHOKIDAR_INTERVAL: "700"')
            }
        }
        $temp = Join-Path $root ('.foundry-host-override-' + [guid]::NewGuid().ToString('N') + '.tmp')
        try {
            [IO.File]::WriteAllText($temp, (($lines -join "`n") + "`n"), (New-Object Text.UTF8Encoding($false)))
            Move-Item -LiteralPath $temp -Destination $override -Force
        } finally {
            if (Test-Path -LiteralPath $temp) { Remove-Item -LiteralPath $temp -Force }
        }
    }
}
Write-Host ("Foundry host: {0} | filesystem: {1} | uid:gid {2}:{3}" -f $profile,$location,$uid,$gid)
if ($profile -in @('windows-native','wsl-windows-fs','linux-shared-fs')) {
    Write-Warning 'Windows/shared source mounts may slow Laravel and Vite. Consider WSL2 ext4 for best I/O.'
}
if ($Mode -eq 'Doctor') {
    if (Get-Command docker -ErrorAction SilentlyContinue) {
        try { & docker info --format 'Docker Engine: {{.ServerVersion}}' 2>$null } catch { Write-Host 'Docker Engine: unavailable' }
    } else { Write-Host 'Docker CLI: unavailable' }
    if ((Test-Path -LiteralPath $override) -and -not (Test-Managed)) { Write-Host 'Compose override: custom (preserved)' }
}
